test('manifest validation reports every problem with a way forward', () => {
  const problems = validateManifest({
    id: 'base:mine',
    name: 'Mine',
    version: '1.0',
    kind: 'widget',
    entyr: 'index.js',
    ports: [{ name: 'in', direction: 'sideways' }],
    properties: {
      latency: { type: 'number', default: 5 },
      mode: { type: 'enum', values: [] }
    },
    icon: 'icn.svg'
  }, { files: ['manifest.json', 'icon.svg'] })
  const text = messages(problems).join('\n')
  for (const expected of [
    /error .*version must be a semantic version/,
    /error .*ports\[0\]\.direction must be in, out or both/,
    /error .*properties\.mode\.values must list the enum options/,
    /error .*strataApi is required/,
    /error .*'base:' are reserved/,
    /error .*kind must be one of component, connection-type/,
    /warning .*Unknown key 'entyr'\. Did you mean 'entry'\?/,
    /warning .*properties\.latency: a number needs an explicit unit/,
    /error .*icon 'icn\.svg' is not in the folder\. Did you mean 'icon\.svg'\?/
  ]) assert.match(text, expected)

  assert.match(messages(validateManifest({ strataApi: '^1.0', id: 'acme.http', name: 'HTTP', version: '1.0.0', kind: 'connection-type', ports: [{ name: 'x', direction: 'in' }] })).join(), /a connection type has no ports/)
  assert.match(messages(validateManifest({ strataApi: '^1.0', id: 'thing', name: 'Thing', version: '1.0.0' })).join(), /has no namespace.*neither "extends" nor "entry"/s)
  assert.match(messages(validateManifest({ strataApi: '^9.0', id: 'acme.x', name: 'X', version: '1.0.0', extends: 'base:service' })).join(), /not compatible with this core/)
  assert.deepEqual(validateManifest(JSON.parse(messageQueueFolder()['manifest.json']), { files: Object.keys(messageQueueFolder()) }), [])
})

test('packing stops at errors and says where they are', () => {
  const broken = { ...messageQueueFolder(), 'manifest.json': '{\n  "id": "acme.q",\n  "name": oops\n}' }
  const r = packComponent(broken)
  assert.equal(r.bundle, null)
  assert.match(messages(r.problems)[0], /^error manifest\.json: Invalid JSON \(line 3, column 11\): /)

  const badModule = { ...messageQueueFolder(), 'lib/backoff.js': 'export function backoff () {\n  return "oops\n}' }
  const r2 = packComponent(badModule)
  assert.equal(r2.bundle, null)
  assert.deepEqual(r2.problems.filter(p => p.level === 'error').map(p => [p.file, p.line]), [['lib/backoff.js', 2]])
  assert.throws(() => requireBundle(r2), /could not be packed:\nlib\/backoff\.js:2: error: Unterminated string/)

  assert.match(messages(packComponent({}).problems)[0], /The folder is empty/)
  assert.match(messages(packComponent({ 'README.md': 'hi' }).problems)[0], /No manifest\.json/)
  const badIcon = { ...messageQueueFolder(), 'icon.svg': '<html></html>' }
  assert.match(messages(packComponent(badIcon).problems).join(), /The icon is not an SVG document/)
})

