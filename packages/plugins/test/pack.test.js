test('uploads: a .strata.js, a zip, or the files of a folder', async () => {
  const { bundle, script } = packComponent(messageQueueFolder(), { name: 'message-queue' })
  assert.ok(bundle && script)

  const fromScript = await packUpload([{ path: 'message-queue.strata.js', content: new TextEncoder().encode(script) }])
  assert.deepEqual(fromScript.bundle, bundle)
  assert.equal(fromScript.fileName, 'message-queue.strata.js')

  const folder = Object.fromEntries(Object.entries(messageQueueFolder()).map(([p, c]) => [`message-queue/${p}`, c]))
  const zipped = makeZip(folder)
  const fromZip = await packUpload([{ path: 'message-queue.zip', content: zipped }])
  assert.equal(fromZip.bundle?.integrity, bundle.integrity, 'the zip packs to the same bundle as the folder')
  assert.equal(fromZip.fileName, 'message-queue.strata.js')

  const viaZlib = await packUpload([{ path: 'q.zip', content: makeZip(folder, { deflate: false }) }], { inflateRaw: data => new Uint8Array(inflateRawSync(data)) })
  assert.equal(viaZlib.bundle?.integrity, bundle.integrity, 'stored entries and an injected inflater')

  const fromFolder = await packUpload(Object.entries(folder).map(([path, content]) => ({ path, content })))
  assert.equal(fromFolder.bundle?.integrity, bundle.integrity)
  assert.equal(fromFolder.fileName, 'message-queue.strata.js')

  const tampered = await packUpload([{ path: 'x.strata.js', content: script.replace('Buffers', 'Loses') }])
  assert.equal(tampered.bundle, null)
  assert.match(tampered.problems[0].message, /integrity mismatch/)
  const notZip = await packUpload([{ path: 'x.zip', content: new Uint8Array([1, 2, 3]) }])
  assert.match(notZip.problems[0].message, /Not a readable zip file/)
})

test('zip archives made by the zip tool read back exactly', async t => {
  let dir
  try {
    execFileSync('zip', ['-v'], { stdio: 'ignore' })
  } catch {
    t.skip('zip is not installed')
    return
  }
  try {
    dir = mkdtempSync(join(tmpdir(), 'strata-zip-'))
    const files = messageQueueFolder()
    for (const [path, content] of Object.entries(files)) {
      mkdirSync(dirname(join(dir, 'message-queue', path)), { recursive: true })
      writeFileSync(join(dir, 'message-queue', path), content)
    }
    execFileSync('zip', ['-qr', 'q.zip', 'message-queue'], { cwd: dir })
    const entries = await readZip(new Uint8Array(readFileSync(join(dir, 'q.zip'))))
    const normalized = normalizeFiles(entries)
    assert.deepEqual(Object.keys(normalized).sort(), Object.keys(files).sort())
    assert.equal(new TextDecoder().decode(normalized['index.js']), files['index.js'])
    const encrypted = makeZip({ 'a.txt': 'x' }, { flags: 1 })
    await assert.rejects(readZip(encrypted), /encrypted/)
  } finally {
    if (dir) rmSync(dir, { recursive: true, force: true })
  }
})

