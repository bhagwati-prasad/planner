test('the JSON error locator agrees with JSON.parse on mutated manifests', () => {
  const random = createPrng(11)
  const source = messageQueueFolder()['manifest.json']
  const alphabet = '{}[]:,"\\ntrue0-.e'
  for (let n = 0; n < 2000; n++) {
    const at = random.nextU32() % source.length
    const ch = alphabet[random.nextU32() % alphabet.length]
    const mutated = random.nextU32() % 2 ? source.slice(0, at) + ch + source.slice(at) : source.slice(0, at) + source.slice(at + 1)
    let valid = true
    try { JSON.parse(mutated) } catch { valid = false }
    assert.equal(jsonErrorOffset(mutated) === -1, valid, JSON.stringify(mutated.slice(Math.max(0, at - 10), at + 10)))
  }
})
