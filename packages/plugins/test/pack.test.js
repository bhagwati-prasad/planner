const messages = problems => problems.map(p => `${p.level} ${p.file}: ${p.message}`)
const shuffled = obj => Object.fromEntries(Object.entries(obj).reverse())

test('packing the spec’s message queue folder', () => {
  const result = packComponent(messageQueueFolder(), { name: 'message-queue' })
  assert.deepEqual(result.problems.filter(p => p.level === 'error'), [])
  const { bundle } = result
  assert.ok(bundle)
  assert.equal(bundle.format, BUNDLE_FORMAT)
  assert.equal(result.fileName, 'message-queue.strata.js')
  assert.equal(bundle.manifest.id, 'acme.message-queue')
  assert.match(bundle.icon ?? '', /^<svg/)
  assert.deepEqual(Object.keys(bundle.modules).sort(), ['index.js', 'lib/backoff.js', 'lib/defaults.json'])
  assert.deepEqual(Object.keys(bundle.assets).sort(), ['README.md', 'templates/runbook.md'], 'self-tests, dotfiles and unused modules stay out')
  assert.equal(bundle.entry, 'index.js')
  assert.match(bundle.integrity, /^sha256-[A-Za-z0-9+/]{43}=$/)
  assert.deepEqual(messages(result.problems), ['warning lib/unused.js: Not imported by the entry or a migration, so it is left out of the bundle'])
  assert.match(result.script ?? '', /^\/\/ message-queue\.strata\.js \(generated by strata pack; do not edit\)\n\/\/ acme\.message-queue@1\.2\.0 · sha256-/)
  assert.match(result.script ?? '', /\nStrata\.registerComponent\(\{/)
})

test('packing is deterministic: the same folder gives the same bytes in any file order', () => {
  const a = packComponent(messageQueueFolder())
  const b = packComponent(shuffled(messageQueueFolder()))
  assert.equal(a.script, b.script)
  const changed = { ...messageQueueFolder(), 'lib/backoff.js': 'export function backoff () { return 1 }\n' }
  assert.notEqual(packComponent(changed).bundle?.integrity, a.bundle?.integrity)
})

test('the packed behaviour runs: modules load through the runtime, as in the worker', () => {
  const { bundle } = packComponent(messageQueueFolder())
  assert.ok(bundle)
  const behaviour = loadModules(bundle.modules, bundle.entry ?? '').default
  const sent = []
  const ctx = {
    state: {},
    props: { capacity: 2 },
    now: 0,
    metric () {},
    schedule: (delay, name) => sent.push(['schedule', delay, name]),
    reject: (msg, code) => sent.push(['reject', msg, code]),
    send: (port, msg) => sent.push(['send', port, msg])
  }
  behaviour.init(ctx)
  behaviour.onMessage('m1', ctx)
  behaviour.onMessage('m2', ctx)
  behaviour.onMessage('m3', ctx)
  behaviour.onTimer('deliver', ctx)
  assert.deepEqual(sent, [['schedule', 10, 'deliver'], ['schedule', 20, 'deliver'], ['reject', 'm3', 'QUEUE_FULL'], ['send', 'out', 'm1']])
})

test('a .strata.js reads back without evaluation and its integrity is checked', () => {
  const { bundle, script } = packComponent(messageQueueFolder())
  assert.ok(bundle && script)
  assert.deepEqual(readBundle(script), bundle)
  assert.deepEqual(readBundle(JSON.stringify(bundle)), bundle)
  assert.deepEqual(readBundle(structuredClone(bundle)), bundle)

  const tampered = script.replace('Math.min(base', 'Math.max(base')
  assert.notEqual(tampered, script)
  assert.throws(() => readBundle(tampered), /changed after it was packed \(integrity mismatch\)\. Pack it again/)
  assert.throws(() => readBundle('console.log("hi")'), /not a packed component/)
  assert.throws(() => readBundle({ ...bundle, modules: { 'index.js': 5 } }), /modules must map paths to text/)
  assert.throws(() => readBundle({ ...bundle, entry: 'missing.js' }), /entry 'missing.js' is not among the modules/)
})

